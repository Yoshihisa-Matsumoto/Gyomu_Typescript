/**
 * Add utility functions for arithmetic operations
 *
 * @param a First number to add
 *
 * @param b Second number to add
 *
 * @returns Sum of a and b
 *
 * @summary function
 *
 * @summary export
 */
export function add(a: number, b: number) {
  return a + b
}

